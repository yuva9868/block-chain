const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const envPath = path.join(__dirname, '..', '.env.local');
if (fs.existsSync(envPath)) {
  console.log('.env.local already exists; not overwriting.');
  process.exit(0);
}

const secret = crypto.randomBytes(32).toString('hex');
const key = crypto.randomBytes(32).toString('hex');
const contents = `# Generated by npm run setup:local. Do not commit this file.
SESSION_SECRET=${secret}
ENCRYPTION_KEY=${key}
RPC_URL=http://127.0.0.1:8545
NEXT_PUBLIC_RPC_URL=http://127.0.0.1:8545
NEXT_PUBLIC_CHAIN_ID=31337
NEXT_PUBLIC_CHAIN_NAME=Hardhat Local
NEXT_PUBLIC_NATIVE_CURRENCY=ETH
NEXT_PUBLIC_CONTRACT_ADDRESS=
NEXT_PUBLIC_EXPLORER_TX_URL=
# Optional: restrict doctor role to Hardhat account #1
# DEMO_DOCTOR_ADDRESSES=0x70997970C51812dc3A010C7d01b50e0d17dc79C8
`;

fs.writeFileSync(envPath, contents);
console.log('Wrote .env.local with SESSION_SECRET and ENCRYPTION_KEY.');
console.log('Next: start Hardhat node, deploy, then paste NEXT_PUBLIC_CONTRACT_ADDRESS.');
